#!/usr/bin/env python3
"""Refresh share/litellm-openai-prices.json from LiteLLM's public price list.

Fetches ONLY the one public URL below (LiteLLM, MIT licence), keeps the
OpenAI-provider token prices, validates them and writes the file atomically.
`cctrl costs` never calls this; it only reads the checked-in file offline.

  python3 lib/refresh_prices.py [--out FILE] [--from-file RAW.json]
"""
import argparse
import json
import os
import sys
import tempfile
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

LITELLM_URL = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
DEFAULT_OUT = Path(__file__).resolve().parent.parent / "share" / "litellm-openai-prices.json"
LICENCE = "MIT (c) BerriAI/litellm, https://github.com/BerriAI/litellm/blob/main/LICENSE"
KEEP = (
    "input_cost_per_token",
    "cache_read_input_token_cost",
    "output_cost_per_token",
    "input_cost_per_token_above_272k_tokens",
    "cache_read_input_token_cost_above_272k_tokens",
    "output_cost_per_token_above_272k_tokens",
)
MIN_MODELS = 20
MAX_BYTES = 64 * 1024 * 1024


def fetch_raw(url=LITELLM_URL):
    if url != LITELLM_URL:
        raise ValueError("only the LiteLLM price list URL may be fetched")
    with urllib.request.urlopen(url, timeout=60) as resp:  # noqa: S310 - fixed https URL
        body = resp.read(MAX_BYTES + 1)
    if len(body) > MAX_BYTES:
        raise ValueError("price list unexpectedly large")
    return json.loads(body)


def build_subset(raw):
    if not isinstance(raw, dict):
        raise ValueError("price list is not a JSON object")
    models = {}
    for name, entry in raw.items():
        if not isinstance(entry, dict) or entry.get("litellm_provider") != "openai":
            continue
        inp, out = entry.get("input_cost_per_token"), entry.get("output_cost_per_token")
        if not isinstance(inp, (int, float)) or not isinstance(out, (int, float)):
            continue
        kept = {}
        for key in KEEP:
            val = entry.get(key)
            if val is None:
                continue
            if isinstance(val, bool) or not isinstance(val, (int, float)) or val < 0:
                raise ValueError(f"bad value for {name}.{key}: {val!r}")
            kept[key] = val
        models[str(name).lower()] = kept
    if len(models) < MIN_MODELS:
        raise ValueError(f"only {len(models)} OpenAI models found; refusing to write")
    return models


def write_atomic(path, models, now=None):
    path = Path(path)
    doc = {
        "_meta": {
            "source": LITELLM_URL,
            "licence": LICENCE,
            "fetched": (now or datetime.now(timezone.utc)).strftime("%Y-%m-%d"),
            "units": "USD per token (LiteLLM native); runtime converts to per 1M",
            "note": "Generated by lib/refresh_prices.py. Do not edit by hand.",
        },
        "models": dict(sorted(models.items())),
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w") as fh:
            json.dump(doc, fh, indent=1)
            fh.write("\n")
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    ap.add_argument("--from-file", help="read a local copy of the LiteLLM list instead of fetching (tests)")
    args = ap.parse_args(argv)
    try:
        if args.from_file:
            with open(args.from_file) as fh:
                raw = json.load(fh)
        else:
            raw = fetch_raw()
        models = build_subset(raw)
        write_atomic(args.out, models)
    except Exception as exc:  # leave any existing file untouched
        print(f"price refresh failed: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {len(models)} OpenAI models to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
